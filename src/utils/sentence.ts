	'แมว__ตัวกินอาหารหมดเลยค่ะ',
	'อันนี้__บาทค่ะ',
	'ฉันอายุ__ปีค่ะ',
	'วันนี้มีนักเรียน__คนค่ะ',
	'ขอน้ำเปล่า__ขวดได้ไหมคะ',
	'บ้านอยู่ห่างจากที่นี่__กิโลเมตรค่ะ',
	'ฉันอยู่ที่นี่มา__วันแล้วค่ะ',
	'พรุ่งนี้อากาศ__องศาค่ะ',
	'ลดราคา__เปอร์เซ็นต์ค่ะ',
	'ซื้อไข่__ฟองค่ะ',
