let sentenceIndex = 0;

export const getSentence = (number: string) => {
	let sentence = SENTENCES[sentenceIndex];
	sentence = sentence.replace('__', number);

	return sentence;
};
export const advanceSentence = () => {
	sentenceIndex = (sentenceIndex + 1) % SENTENCES.length;
};
