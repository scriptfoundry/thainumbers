	'ฉันโทรหาคุณ__ครั้งแล้วนะคะ',
	'เจอกันวันที่__นะคะ',
	'ฉันอยู่ห้องเลขที่__ค่ะ',
	'ขอเมนูหมายเลข__ค่ะ',
